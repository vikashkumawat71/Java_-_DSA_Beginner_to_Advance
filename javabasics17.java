public class javabasics17 {
    public static void main(String[] args){
        int A = 10;
        //A = A + 5;
        A += 5;
        System.out.println(A);

        int B = 10;
        //B = B - 5;    
        B -= 5;
        System.out.println(B);

        int C = 10;
        //C = C * 5;
        C *= 5;
        System.out.println(C);

        int D = 10;
        //D = D / 5;    
        D /= 5;
        System.out.println(D);

        int E = 10;
        //E = E % 5;
        E %= 5;
        System.out.println(E);

        
    }
}
